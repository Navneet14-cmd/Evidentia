"""Shared reportlab styling for certificates and case reports."""
from __future__ import annotations

import re

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import Paragraph, Table, TableStyle

NAVY = colors.HexColor("#0f172a")
SLATE = colors.HexColor("#334155")
MUTED = colors.HexColor("#64748b")
LINE = colors.HexColor("#cbd5e1")
ACCENT = colors.HexColor("#0ea5e9")
OK = colors.HexColor("#16a34a")
BAD = colors.HexColor("#dc2626")
WARN = colors.HexColor("#d97706")
ZEBRA = colors.HexColor("#f1f5f9")

_ss = getSampleStyleSheet()
H1 = ParagraphStyle("H1", parent=_ss["Heading1"], fontName="Helvetica-Bold", fontSize=15, textColor=NAVY,
                    spaceBefore=10, spaceAfter=6)
H2 = ParagraphStyle("H2", parent=_ss["Heading2"], fontName="Helvetica-Bold", fontSize=11.5, textColor=SLATE,
                    spaceBefore=7, spaceAfter=3)
BODY = ParagraphStyle("Body", parent=_ss["BodyText"], fontName="Helvetica", fontSize=9, leading=12,
                      alignment=TA_LEFT)
SMALL = ParagraphStyle("Small", parent=BODY, fontSize=7.5, leading=9.5, textColor=MUTED)
MONO = ParagraphStyle("Mono", parent=BODY, fontName="Courier", fontSize=7.2, leading=9)
CELL = ParagraphStyle("Cell", parent=BODY, fontSize=7.8, leading=9.6)
CELLB = ParagraphStyle("CellB", parent=CELL, fontName="Helvetica-Bold", textColor=SLATE)


_MARKUP = re.compile(r"<(?:br/|/?b>|/?i>|/?font\b)")


def P(text, style=BODY):
    """Paragraph; text containing inline markup (<b>, <br/>, <font>) is used as-is, else escaped."""
    text = str(text)
    if not _MARKUP.search(text):
        text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return Paragraph(text, style)


def kv_table(rows, widths=(120, 380)):
    data = [[P(k, CELLB), v if not isinstance(v, str) else P(v, CELL)] for k, v in rows]
    t = Table(data, colWidths=widths)
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"), ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
        ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
    return t


def grid_table(header, rows, widths, zebra=True):
    data = [[P(h, CELLB) for h in header]] + [[c if not isinstance(c, (str, int, float)) else P(c, CELL)
                                               for c in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
             ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("LINEBELOW", (0, 0), (-1, -1), 0.3, LINE),
             ("TOPPADDING", (0, 0), (-1, -1), 2.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5)]
    if zebra:
        style += [("BACKGROUND", (0, i), (-1, i), ZEBRA) for i in range(2, len(data), 2)]
    t.setStyle(TableStyle(style))
    return t


def header_band(canvas, doc, title: str, subtitle: str):
    w, h = doc.pagesize
    canvas.saveState()
    canvas.setFillColor(NAVY)
    canvas.rect(0, h - 62, w, 62, stroke=0, fill=1)
    canvas.setFillColor(ACCENT)
    canvas.rect(0, h - 65, w, 3, stroke=0, fill=1)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 16)
    canvas.drawString(36, h - 32, title)
    canvas.setFont("Helvetica", 8.5)
    canvas.setFillColor(colors.HexColor("#cbd5e1"))
    canvas.drawString(36, h - 48, subtitle)
    canvas.setFont("Helvetica-Bold", 11)
    canvas.setFillColor(colors.white)
    canvas.drawRightString(w - 36, h - 32, "EVIDENTIA")
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(colors.HexColor("#94a3b8"))
    canvas.drawRightString(w - 36, h - 44, "Forensic recovery & sanitization")
    canvas.setFillColor(MUTED)
    canvas.setFont("Helvetica", 7)
    canvas.drawString(36, 22, f"Generated by Evidentia — page {doc.page}")
    canvas.restoreState()
